"""Reports whose figures come from the catalog: a Jinja2 template renders to Markdown.

Template globals:
  query(sql, **params) -> list of row dicts   (named parameters as $name)
  value(sql, **params) -> the single value of a one-row, one-column result
  record(gid)          -> a record row; the record is listed as a source of the report
  pct(x, digits=0), num(x, digits=2) -> formatting helpers
Undefined names are errors (StrictUndefined), so a missing figure cannot render as a blank. The
rendered file ends with a provenance comment naming the template and the records it used.
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path
from typing import Any

import duckdb
from jinja2 import Environment, FileSystemLoader, StrictUndefined


class _Ctx:
    def __init__(self, con: duckdb.DuckDBPyConnection):
        self.con = con
        self.used: set[str] = set()

    def query(self, sql: str, **params) -> list[dict]:
        cur = self.con.execute(sql, params or None)
        cols = [d[0] for d in cur.description]
        return [dict(zip(cols, row, strict=True)) for row in cur.fetchall()]

    def value(self, sql: str, **params):
        rows = self.con.execute(sql, params or None).fetchall()
        if len(rows) != 1 or len(rows[0]) != 1:
            raise ValueError(
                f"value() needs exactly one row and column, got {len(rows)} rows: {sql}"
            )
        return rows[0][0]

    def record(self, gid: str) -> dict:
        rows = self.query("SELECT * FROM records WHERE gid = $gid", gid=gid)
        if not rows:
            raise KeyError(f"no record {gid}")
        self.used.add(gid)
        return rows[0]


def _pct(x, digits: int = 0) -> str:
    return f"{100 * float(x):.{digits}f}%"


def _num(x, digits: int = 2) -> str:
    return f"{float(x):.{digits}f}"


def render(template: Path, catalog: Path, out: Path) -> Path:
    con = duckdb.connect(str(catalog), read_only=True)
    try:
        ctx = _Ctx(con)
        env = Environment(
            loader=FileSystemLoader(str(template.parent)),
            undefined=StrictUndefined,
            keep_trailing_newline=True,
            autoescape=False,
            trim_blocks=True,
            lstrip_blocks=True,
        )
        helpers: dict[str, Any] = {
            "query": ctx.query,
            "value": ctx.value,
            "record": ctx.record,
            "pct": _pct,
            "num": _num,
        }
        env.globals.update(helpers)
        text = env.get_template(template.name).render()
    finally:
        con.close()
    sources = ", ".join(sorted(ctx.used)) or "none"
    text = text.rstrip() + (
        f"\n\n<!-- generated by `just evidence render {template.name}` on {dt.date.today()}; "
        f"records: {sources} -->\n"
    )
    out.write_text(text, encoding="utf-8")
    return out
