"""Database probes for the comparative library-leverage review (throwaway databases on 5434).

Q1 (CBO-008): does Alembic's configured comparison (`command.check` through the semantic env.py)
report a clean result against a database migrated to head, and if not, which diffs appear?
Q2 (CBO-010): does `CREATE DATABASE ... TEMPLATE <migrated head>` preserve the database-level TEMP
privileges the revisions establish, and does a generic `aclexplode` replay restore them? Object
privileges are sampled as a control.
"""

from __future__ import annotations

import json
import os
import time
from uuid import uuid4

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, text
from sqlalchemy.exc import DBAPIError
from sqlalchemy.pool import NullPool

from corpus_structure.core.db import extensions
from corpus_structure.semantic.migrations import alembic_config, current_revision, head_revision, upgrade
from corpus_structure.semantic.runtime import connection_settings
from corpus_structure.settings import Settings

ROLES = ("corpus_sem_publisher", "corpus_sem_writer", "corpus_sem_reader", "corpus_sem_evaluator")
out: dict[str, object] = {}
settings = Settings()
admin_url = connection_settings(settings, "maintenance").database.sqlalchemy_url
admin = create_engine(admin_url, poolclass=NullPool)
server = create_engine(admin.url.set(database="postgres"), poolclass=NullPool)
quote = server.dialect.identifier_preparer.quote
stem = f"cs_sem_probe_{os.getpid()}_{uuid4().hex[:8]}"
tmpl, clone = stem + "_t", stem + "_c"
created: list[str] = []


def privileges(db: str) -> dict:
    with server.connect() as conn:
        acl = conn.execute(text("SELECT datacl::text FROM pg_database WHERE datname=:d"), {"d": db}).scalar_one()
        temp = {
            r: conn.execute(text("SELECT has_database_privilege(:r, :d, 'TEMP')"), {"r": r, "d": db}).scalar_one()
            for r in ROLES
            if conn.execute(text("SELECT 1 FROM pg_roles WHERE rolname=:r"), {"r": r}).first()
        }
    return {"datacl": acl, "temp": temp}


def object_sample(db: str) -> dict:
    engine = create_engine(admin.url.set(database=db), poolclass=NullPool)
    try:
        with engine.connect() as conn:
            return {
                "reader_insert_data_entity": conn.execute(text("SELECT has_table_privilege('corpus_sem_reader','data.entity','INSERT')")).scalar_one(),
                "reader_select_data_entity": conn.execute(text("SELECT has_table_privilege('corpus_sem_reader','data.entity','SELECT')")).scalar_one(),
                "writer_execute_begin_stage": conn.execute(text("SELECT has_function_privilege('corpus_sem_writer','data.begin_stage()','EXECUTE')")).scalar_one(),
            }
    finally:
        engine.dispose()


def drop(db: str) -> None:
    for attempt in range(40):
        try:
            with server.connect().execution_options(isolation_level="AUTOCOMMIT") as conn:
                conn.exec_driver_sql(f"DROP DATABASE IF EXISTS {quote(db)}")
            return
        except DBAPIError as exc:
            if getattr(exc.orig, "sqlstate", None) != "55006" or attempt == 39:
                raise
            time.sleep(0.05)


try:
    with server.connect().execution_options(isolation_level="AUTOCOMMIT") as conn:
        conn.exec_driver_sql(f"CREATE DATABASE {quote(tmpl)} TEMPLATE {quote(settings.database.template)}")
        created.append(tmpl)
    engine = create_engine(admin.url.set(database=tmpl), poolclass=NullPool)
    with engine.begin() as conn:
        extensions.check(conn.execute(text(extensions.FOUND)).all())
        upgrade(conn)
    with engine.connect() as conn:
        out["head"] = head_revision()
        out["current"] = current_revision(conn)
        try:
            command.check(alembic_config(conn))
            out["q1_check"] = "clean"
        except AutogenerateDiffsDetected as exc:
            diffs = getattr(exc, "diffs", None)
            out["q1_check"] = "diffs"
            out["q1_diff_count"] = len(diffs) if diffs is not None else None

            def describe(d):
                if isinstance(d, list):
                    return [describe(x) for x in d]
                op, *rest = d
                obj = rest[-1] if rest else None
                name = getattr(obj, "name", None)
                table = getattr(getattr(obj, "table", None), "fullname", None)
                text_ = str(getattr(obj, "sqltext", "")) or None
                return {"op": op, "name": name, "table": table, "sqltext": text_, "detail": [str(x) for x in rest[:-1]][:4]}

            out["q1_diffs"] = [describe(d) for d in (diffs or [])]
    engine.dispose()
    out["q2_template"] = privileges(tmpl)
    out["q2_template_objects"] = object_sample(tmpl)
    with server.connect().execution_options(isolation_level="AUTOCOMMIT") as conn:
        conn.exec_driver_sql(f"CREATE DATABASE {quote(clone)} TEMPLATE {quote(tmpl)}")
        created.append(clone)
    out["q2_clone_before_replay"] = privileges(clone)
    out["q2_clone_objects"] = object_sample(clone)
    with server.connect().execution_options(isolation_level="AUTOCOMMIT") as conn:
        grants = conn.execute(text(
            "SELECT CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(g.rolname) END, a.privilege_type "
            "FROM pg_database d, aclexplode(d.datacl) a LEFT JOIN pg_roles g ON g.oid = a.grantee "
            "WHERE d.datname = :d AND a.grantee <> d.datdba"), {"d": tmpl}).all()
        conn.exec_driver_sql(f"REVOKE ALL ON DATABASE {quote(clone)} FROM PUBLIC")
        for grantee, privilege in grants:
            conn.exec_driver_sql(f"GRANT {privilege} ON DATABASE {quote(clone)} TO {grantee}")
    out["q2_replayed_grants"] = [list(g) for g in grants]
    out["q2_clone_after_replay"] = privileges(clone)
    out["q2_datacl_set_equal_after_replay"] = sorted(out["q2_clone_after_replay"]["datacl"].strip("{}").split(",")) == sorted(out["q2_template"]["datacl"].strip("{}").split(","))
finally:
    for db in reversed(created):
        drop(db)
    with server.connect() as conn:
        out["residue"] = conn.execute(text("SELECT count(*) FROM pg_database WHERE datname LIKE :p"), {"p": stem + "%"}).scalar_one()
    server.dispose()
    admin.dispose()
    print(json.dumps(out, indent=2, default=str))
