"""Schema-parity and native-semantics probe for the design-principle audit (throwaway databases on 5434).

P3 (S2-1): does the deployed head schema equal the shared MetaData body for body?
  Database A is upgraded to head through `semantic.migrations.upgrade`; database B gets the same
  schemas and `metadata.create_all`. Their catalogs are compared on columns (type, nullability,
  default), constraints (definition, name) and indexes (definition with the name blanked).
  Alembic's configured check (`command.check` through the semantic env.py) also runs against A.
P4 (S3-02): do Python `canonical_bytes` and native `data.canonical_json` agree on non-integer numbers?
P5 (S3-02): does native locator whitespace normalization equal Python `core.locators.normalize`
  for NBSP, ideographic space, em space, NEL and information separators?
P6 (S3-12): which error class does native `decimal_canonical` raise for a huge exponent?
"""

from __future__ import annotations

import json
import os
import re
import sys
import time
from collections import Counter
from uuid import uuid4

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, text
from sqlalchemy.exc import DBAPIError
from sqlalchemy.pool import NullPool

from corpus_structure.core.locators import normalize
from corpus_structure.semantic.identity import canonical_bytes
from corpus_structure.semantic.metadata import SCHEMAS, metadata
from corpus_structure.semantic.migrations import alembic_config, current_revision, upgrade
from corpus_structure.semantic.runtime import connection_settings
from corpus_structure.settings import Settings

out: dict[str, object] = {}
settings = Settings()
admin = create_engine(connection_settings(settings, "maintenance").database.sqlalchemy_url, poolclass=NullPool)
server = create_engine(admin.url.set(database="postgres"), poolclass=NullPool)
quote = server.dialect.identifier_preparer.quote
stem = f"cs_sem_probe_{os.getpid()}_{uuid4().hex[:8]}"
dbs = {"migrated": stem + "_m", "created": stem + "_c"}
made: list[str] = []


def drop(db: str) -> None:
    for attempt in range(40):
        try:
            with server.connect().execution_options(isolation_level="AUTOCOMMIT") as conn:
                conn.exec_driver_sql(f"DROP DATABASE IF EXISTS {quote(db)}")
            return
        except DBAPIError as exc:
            if getattr(exc.orig, "sqlstate", None) != "55006" or attempt == 39:
                raise
            time.sleep(0.05)


def catalog(conn) -> dict:
    schemas = sorted(SCHEMAS)
    cols = conn.execute(text("""
        SELECT n.nspname||'.'||c.relname, a.attname, format_type(a.atttypid,a.atttypmod), a.attnotnull,
               pg_get_expr(d.adbin,d.adrelid)
        FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace
        LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
        WHERE c.relkind IN ('r','p') AND n.nspname = ANY(:s) AND a.attnum>0 AND NOT a.attisdropped"""), {"s": schemas}).all()
    cons = conn.execute(text("""
        SELECT n.nspname||'.'||c.relname, k.contype::text, k.conname, pg_get_constraintdef(k.oid)
        FROM pg_constraint k JOIN pg_class c ON c.oid=k.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname = ANY(:s)"""), {"s": schemas}).all()
    idx = conn.execute(text("""
        SELECT schemaname||'.'||tablename, indexname, indexdef FROM pg_indexes WHERE schemaname = ANY(:s)"""), {"s": schemas}).all()
    return {
        "columns": {f"{t}.{c}": [ty, nn, df] for t, c, ty, nn, df in cols},
        "constraints": [[t, ty, name, d] for t, ty, name, d in cons],
        "indexes": [[t, name, re.sub(r"INDEX \S+ ON", "INDEX ? ON", d)] for t, name, d in idx],
    }


def compare(a: dict, b: dict) -> dict:
    res: dict[str, object] = {}
    ca, cb = a["columns"], b["columns"]
    res["columns_only_migrated"] = sorted(set(ca) - set(cb))
    res["columns_only_created"] = sorted(set(cb) - set(ca))
    res["columns_differ"] = {k: {"migrated": ca[k], "created": cb[k]} for k in sorted(set(ca) & set(cb)) if ca[k] != cb[k]}
    def defs(rows, key):  # multiset of (table, type, definition), name ignored
        return Counter((r[0], r[1], r[3]) for r in rows) if key == "con" else Counter((r[0], r[2]) for r in rows)
    da, db_ = defs(a["constraints"], "con"), defs(b["constraints"], "con")
    res["constraint_defs_only_migrated"] = sorted([list(k) for k in (da - db_)])
    res["constraint_defs_only_created"] = sorted([list(k) for k in (db_ - da)])
    names_a = {(r[0], r[1], r[3]): r[2] for r in a["constraints"]}
    names_b = {(r[0], r[1], r[3]): r[2] for r in b["constraints"]}
    res["same_definition_different_name"] = sorted(
        [[k[0], k[1], names_a[k], names_b[k]] for k in set(names_a) & set(names_b) if names_a[k] != names_b[k]])
    ia, ib = defs(a["indexes"], "idx"), defs(b["indexes"], "idx")
    res["index_defs_only_migrated"] = sorted([list(k) for k in (ia - ib)])
    res["index_defs_only_created"] = sorted([list(k) for k in (ib - ia)])
    res["counts"] = {"migrated": {k: len(v) for k, v in a.items()}, "created": {k: len(v) for k, v in b.items()}}
    return res


try:
    with server.connect().execution_options(isolation_level="AUTOCOMMIT") as conn:
        for db in dbs.values():
            conn.exec_driver_sql(f"CREATE DATABASE {quote(db)} TEMPLATE {quote(settings.database.template)}")
            made.append(db)
    eng_m = create_engine(admin.url.set(database=dbs["migrated"]), poolclass=NullPool)
    eng_c = create_engine(admin.url.set(database=dbs["created"]), poolclass=NullPool)
    try:
        with eng_m.begin() as conn:
            upgrade(conn)
        with eng_c.begin() as conn:
            for schema in sorted(SCHEMAS):
                conn.exec_driver_sql(f"CREATE SCHEMA IF NOT EXISTS {quote(schema)}")
            metadata.create_all(conn)
        with eng_m.connect() as conn:
            out["head"] = current_revision(conn)
            cat_m = catalog(conn)
            try:
                command.check(alembic_config(conn))
                out["p3_alembic_check"] = "clean"
            except AutogenerateDiffsDetected as exc:
                diffs = getattr(exc, "diffs", None) or []
                out["p3_alembic_check"] = "diffs"
                flat = [d for d in diffs for d in (d if isinstance(d, list) else [d])]
                out["p3_alembic_diff_ops"] = dict(Counter(d[0] for d in flat))
        # The native functions are executable by the restricted roles, not by the owner login.
        with eng_m.connect() as conn, conn.begin():
            conn.execute(text("SET LOCAL ROLE corpus_sem_publisher"))
            # P4: canonical JSON over non-integer numbers
            sample = "[1e-05,1.0E2,-0.0,0.1,12345678901234567890.5]"
            native = conn.execute(text("SELECT data.canonical_json(CAST(:j AS jsonb))"), {"j": sample}).scalar_one()
            out["p4"] = {"input": sample, "native": native, "python": canonical_bytes(json.loads(sample)).decode(),
                         "equal": native == canonical_bytes(json.loads(sample)).decode()}
            # P5: whitespace normalization (native expression copied from ops.source_locator_segment)
            loc = conn.execute(text("SELECT datlocprovider::text, datctype, datcollate FROM pg_database WHERE datname=current_database()")).one()
            p5 = {"locale": list(loc), "cases": {}}
            for name, ch in {"NBSP": " ", "IDEOGRAPHIC": "　", "EM_SPACE": " ", "NEL": "\u0085",
                             "FILE_SEP": "\u001c", "TAB": "\t", "ZWSP": "​"}.items():
                s = f"a{ch}b"
                nat = conn.execute(text("SELECT btrim(regexp_replace(normalize(CAST(:s AS text),NFC),'[[:space:]]+',' ','g'))"), {"s": s}).scalar_one()
                py = normalize(s)
                p5["cases"][name] = {"native": nat.encode("unicode_escape").decode(), "python": py.encode("unicode_escape").decode(), "equal": nat == py}
            out["p5"] = p5
            # P6: huge exponent
            p6 = {}
            for lexical in ("1e400000000", "1e2147483648"):
                try:
                    with conn.begin_nested():
                        value = conn.execute(text("SELECT length(data.decimal_canonical(:x))"), {"x": lexical}).scalar_one()
                    p6[lexical] = {"result_length": value}
                except DBAPIError as exc:
                    p6[lexical] = {"sqlstate": getattr(exc.orig, "sqlstate", None), "error": str(exc.orig).splitlines()[0]}
            out["p6"] = p6
        with eng_c.connect() as conn:
            cat_c = catalog(conn)
        out["p3"] = compare(cat_m, cat_c)
    finally:
        eng_m.dispose()
        eng_c.dispose()
finally:
    for db in made:
        drop(db)
    with server.connect() as conn:
        out["residue"] = conn.execute(text("SELECT count(*) FROM pg_database WHERE datname LIKE 'cs_sem_probe_%'")).scalar_one()
    json.dump(out, sys.stdout, indent=1, default=str)
