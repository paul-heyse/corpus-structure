"""S5-A step 0: every math span of the 78 first-pass pages, with each rendition's macro sources.

    UV_PROJECT_ENVIRONMENT=$REPO/build/spike-venv uv run --project <spike folder> --locked python code/s5_spans.py

Pages outside the stored seven are regenerated by ``s1_adapter.adapt`` under the S1 configuration
(contract R1, parser recorded); on the stored seven (results/s1, results/s0r2/s1) the regenerated
canonical text and math segments are compared with the stored ones and the stored ones are used.
Writes results/s5/spans.jsonl (one row per math span) and results/s5/renditions.json (per page:
rendition key, parser, libxml2, span counts, the spike reader's macro table and the raw source of
every ``div.latex`` block, which step 1's TeX-tokenizer reader reads).
"""

from __future__ import annotations

import csv
import hashlib
import json
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

CODE = Path(__file__).resolve().parent
sys.path.insert(0, str(CODE))

EVIDENCE = CODE.parent
REPO = EVIDENCE.parents[3]
OUT = EVIDENCE / "results" / "s5"
INDEX = REPO / "docs/statistics_corpus/index/siegrist_sections.tsv"
STORED = [(EVIDENCE / "results" / "s1"), (EVIDENCE / "results" / "s0r2" / "s1")]


def first_pass() -> list[str]:
    with INDEX.open() as f:
        return [r["path"] for r in csv.DictReader(f, delimiter="\t") if r["first_pass"] == "yes"]


def stored(page: str):
    stem = page.replace("/", "__").removesuffix(".html")
    for d in STORED:
        txt, seg = d / "canonical" / f"{stem}.txt", d / "segments" / f"{stem}.jsonl"
        ren = json.loads((d / "renditions.json").read_text())
        if txt.exists() and seg.exists() and page in ren:
            return (txt.read_text(encoding="utf-8"), [json.loads(x) for x in seg.read_text().splitlines() if x.strip()],
                    ren[page], str(d.relative_to(EVIDENCE)))
    return None


def latex_blocks(page: str, parser: str) -> list[str]:
    from s1_adapter import SIEGRIST, parse_html

    root = parse_html((SIEGRIST / page).read_bytes(), parser)
    return ["".join(div.itertext()) for div in
            root.xpath("//div[contains(concat(' ', normalize-space(@class), ' '), ' latex ')]")]


def math_rows(page: str, text: str, segs: list[dict]) -> list[dict]:
    return [{"page": page, "key": s["key"], "kind": s["kind"], "start": s["start"], "end": s["end"],
             "delimiting": s.get("parse_status", "ok"), "reason": s.get("parse_reason") or s.get("reason"),
             "latex": text[s["start"]:s["end"]]} for s in segs if s["kind"].startswith("math")]


def one(page: str) -> dict:
    from s1_adapter import adapt

    r = adapt(page)
    ren = r["rendition"]
    regenerated = math_rows(page, r["text"], r["segments"])
    out = {"page": page, "parser": ren["parser"], "libxml2": ren["libxml2"], "rendition_key": ren["rendition_key"],
           "text_sha256": hashlib.sha256(r["text"].encode()).hexdigest(), "source": "regenerated (s1_adapter.adapt, R1)",
           "macros_spike_reader": ren["parse_detail"]["macros"], "latex_blocks": latex_blocks(page, ren["parser"]),
           "math_anomalies": ren["parse_detail"]["math_anomalies"]}
    st = stored(page)
    rows = regenerated
    if st is not None:
        text, segs, sren, where = st
        kept = math_rows(page, text, segs)
        out["stored"] = {"where": where, "rendition_key": sren["rendition_key"],
                         "text_identical": text == r["text"],
                         "math_spans_identical": [(x["key"], x["start"], x["end"], x["latex"]) for x in kept]
                         == [(x["key"], x["start"], x["end"], x["latex"]) for x in regenerated],
                         "macros_identical": sren["parse_detail"]["macros"] == ren["parse_detail"]["macros"]}
        out["source"] = f"stored ({where})"
        rows = kept
    out["spans"] = len(rows)
    out["spans_by_delimiting"] = {k: sum(1 for x in rows if x["delimiting"] == k) for k in sorted({x["delimiting"] for x in rows})}
    return {"rendition": out, "rows": rows}


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    pages = first_pass()
    with ProcessPoolExecutor(max_workers=24) as ex:
        results = list(ex.map(one, pages))
    rens = {r["rendition"]["page"]: r["rendition"] for r in results}
    with (OUT / "spans.jsonl").open("w", encoding="utf-8") as f:
        for r in results:
            for row in r["rows"]:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
    (OUT / "renditions.json").write_text(json.dumps(rens, indent=1, ensure_ascii=False) + "\n")
    n = sum(r["rendition"]["spans"] for r in results)
    deli = {}
    for r in results:
        for k, v in r["rendition"]["spans_by_delimiting"].items():
            deli[k] = deli.get(k, 0) + v
    print(json.dumps({"pages": len(pages), "spans": n, "delimiting": deli,
                      "parsers": sorted({r["parser"] for r in rens.values()}),
                      "stored": {p: r["stored"] for p, r in rens.items() if "stored" in r}}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
