"""Migration 0001 (P0-F-4): its round trip, `alembic check`, and the catalog comparison.

Each test works on throwaway databases cloned from `cs_template` under this session's lease
(conftest, DA-019) and dropped afterwards. The catalog comparison reads the server's own deparse
(`format_type`, `pg_get_expr`, `pg_get_constraintdef`, `pg_get_indexdef`, `pg_get_viewdef`), so it
sees what `alembic check` does not: CHECK bodies, index methods, `WITH` options and partial
predicates (store note §1).
"""

from __future__ import annotations

import os
import shutil
from collections.abc import Generator
from contextlib import contextmanager
from pathlib import Path
from typing import Any

import pytest
from alembic import command
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Connection, Engine, create_engine, text
from sqlalchemy.pool import NullPool

from corpus_structure.core import db
from corpus_structure.core._model import revision
from corpus_structure.core.db import migrations, overlay

SCHEMAS = ("meta", "kb", "ops", "eval")
_n = iter(range(9201, 9300))


@contextmanager
def clone(db_server: Any) -> Generator[Engine]:
    name = f"ci_test_{os.getpid()}_{next(_n)}"
    db_server.create(name, db_server.template)
    engine = create_engine(db_server.url_of(name), poolclass=NullPool)
    try:
        yield engine
    finally:
        engine.dispose()
        db_server.drop(name)


CATALOG = {
    "columns": """
        SELECT n.nspname || '.' || c.relname, a.attnum, a.attname,
               format_type(a.atttypid, a.atttypmod), a.attnotnull, a.attidentity,
               pg_get_expr(d.adbin, d.adrelid)
        FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE n.nspname = ANY(:s) AND a.attnum > 0 AND NOT a.attisdropped
          AND c.relkind IN ('r', 'v')""",
    "constraints": """
        SELECT conrelid::regclass::text, conname, pg_get_constraintdef(oid)
        FROM pg_constraint WHERE connamespace::regnamespace::text = ANY(:s)""",
    "indexes": "SELECT schemaname, indexname, indexdef FROM pg_indexes WHERE schemaname = ANY(:s)",
    "views": "SELECT schemaname || '.' || viewname, definition FROM pg_views "
    "WHERE schemaname = ANY(:s)",
}


def catalog(conn: Connection) -> dict[str, set[tuple[Any, ...]]]:
    return {
        k: {tuple(r) for r in conn.execute(text(q), {"s": list(SCHEMAS)})}
        for k, q in CATALOG.items()
    }


def differences(a: dict, b: dict) -> dict[str, list]:
    return {k: sorted(a[k] ^ b[k], key=str) for k in a if a[k] != b[k]}


def schemas(conn: Connection) -> set[str]:
    rows = conn.execute(
        text("SELECT nspname FROM pg_namespace WHERE nspname = ANY(:s)"), {"s": list(SCHEMAS)}
    )
    return {r[0] for r in rows}


def test_upgrade_downgrade_upgrade(db_server: Any) -> None:
    with clone(db_server) as engine:
        with engine.begin() as conn:
            applied = migrations.upgrade(conn)
        assert [a["revision"] for a in applied] == ["0001", "0002", "0003"]
        assert applied[0]["model_revision"] is not None
        with engine.begin() as conn:
            assert schemas(conn) == set(SCHEMAS)
            assert migrations.current_revision(conn) == migrations.head_revision() == "0003"
            migrations.downgrade(conn)
        with engine.connect() as conn:
            assert schemas(conn) == set()
            installed = dict(
                conn.execute(text("SELECT extname, extversion FROM pg_extension")).all()
            )
            assert set(overlay.expected_extensions()) <= set(installed)  # the extensions stay
        with engine.begin() as conn:
            migrations.upgrade(conn)
            assert schemas(conn) == set(SCHEMAS)


def test_the_catalog_after_upgrade_equals_create_all(db_server: Any) -> None:
    with clone(db_server) as migrated, clone(db_server) as created:
        with migrated.begin() as conn:
            migrations.upgrade(conn)
        with created.begin() as conn:
            db.metadata.create_all(conn, tables=[*overlay.deployed(db.metadata), *db.OVERLAY.views])
        with migrated.connect() as a, created.connect() as b:
            left, right = catalog(a), catalog(b)
        assert differences(left, right) == {}
        assert len(left["indexes"]) > 100 and len(left["views"]) == 3
        assert not any("embedding" in str(r) for r in left["columns"])  # deferred to phase 1


def test_alembic_check_is_clean_and_blind_to_a_changed_check_body(db_server: Any) -> None:
    with clone(db_server) as migrated, clone(db_server) as created:
        with migrated.begin() as conn:
            migrations.upgrade(conn)
        with created.begin() as conn:
            db.metadata.create_all(conn, tables=[*overlay.deployed(db.metadata), *db.OVERLAY.views])
        with migrated.begin() as conn:
            command.check(migrations.alembic_config(conn))  # clean
        polarity = next(
            c.name
            for c in db.metadata.tables["kb.claim"].constraints
            if str(c.name).startswith("ck_claim_polarity_")
        )
        with migrated.begin() as conn:
            conn.execute(
                text(
                    f"ALTER TABLE kb.claim DROP CONSTRAINT {polarity}, ADD CONSTRAINT "
                    f"{polarity} CHECK (polarity IN ('positive'))"
                )
            )
            conn.execute(text("DROP INDEX ops.task_lease"))
            conn.execute(
                text("CREATE INDEX task_lease ON ops.task (lease_until) WHERE status = 'pending'")
            )
        with migrated.begin() as conn:
            command.check(migrations.alembic_config(conn))  # the changes pass alembic check
        with migrated.connect() as a, created.connect() as b:
            found = differences(catalog(a), catalog(b))
        assert set(found) == {"constraints", "indexes"}
        assert any(str(polarity) in str(r) for r in found["constraints"])
        assert any("task_lease" in str(r) for r in found["indexes"])


def test_a_missing_table_is_reported_by_alembic_check(db_server: Any) -> None:
    with clone(db_server) as migrated:
        with migrated.begin() as conn:
            migrations.upgrade(conn)
            conn.execute(text("DROP TABLE kb.entity_mention"))
        with migrated.begin() as conn, pytest.raises(AutogenerateDiffsDetected):
            command.check(migrations.alembic_config(conn))


def test_a_revision_for_an_unregistered_model_revision_is_refused(
    db_server: Any, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    location = tmp_path / "alembic"
    shutil.copytree(migrations.ALEMBIC_DIR, location, ignore=shutil.ignore_patterns("__pycache__"))
    monkeypatch.setattr(revision, "CONTENT_HASH", "f" * 64)
    with clone(db_server) as engine, engine.begin() as conn:
        migrations.upgrade(conn)
        config = migrations.alembic_config(conn)
        config.set_main_option("script_location", str(location))
        config.set_main_option("revision_environment", "true")
        with pytest.raises(migrations.UnregisteredModelRevision, match=r"not in revisions\.yaml"):
            command.revision(config, "seeded", autogenerate=True, rev_id="0002")
    assert sorted(p.name for p in (location / "versions").glob("*.py")) == [
        "0001_initial_schema.py",
        "0002_preserve_reference_descriptors.py",
        "0003_preserve_statement_order_and_reference_roles.py",
    ]
