def _statement_or_outside(raw: Any) -> str:
    """The tag of a union member: its `anchor` when that is outside, else 'statement'."""
    value = raw.get("anchor") if isinstance(raw, dict) else getattr(raw, "anchor", None)
    return value if value in ("outside",) else "statement"


