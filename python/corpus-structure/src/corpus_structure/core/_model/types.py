"""The model's constrained types, the shapes' base model and reference markers (model and
projections §3.3).

Each type of `model/core.yaml` and `model/system.yaml` with a pattern, a bound or a
Python type is an `Annotated` alias (its pattern also a constant); `CoreModel` is every
shape's frozen, closed base; `Refers` marks a reference position with the kinds it may
name (`values.ref_kinds` reads it) and `CITATION` a citation position
(`batch.rewrite_citations` finds them by it); `keyed` loads a dict-inlined collection
(LinkML's mapping form, a single-valued body included) as its tuple of records.

Generated by `corpus_structure.schema.stage_b` from the model (`just model generate`); do not
edit.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from typing import Annotated, Final

from pydantic import BaseModel, ConfigDict, Field, JsonValue

from corpus_structure.core.vocab import RefKind


class CoreModel(BaseModel):
    """The base of every generated shape: frozen, unknown fields refused."""

    model_config = ConfigDict(frozen=True, extra="forbid")


@dataclass(frozen=True, slots=True)
class Refers:
    """The marker on a reference type's annotation: the kinds the position may name."""

    kinds: frozenset[RefKind]


class _Citation:
    """The marker on a citation type's annotation: a field of the type cites a
    sentence."""

    def __repr__(self) -> str:
        return "CITATION"


CITATION: Final = _Citation()


def keyed(key: str, single: str | None = None) -> Callable[[object], object]:
    """The loader of a dict-inlined collection: `{<key>: {…}}`, or `{<key>: <single>}`
    when the record has one other slot, as the list of records with `key`; a list
    passes."""

    def load(value: object) -> object:
        if not isinstance(value, Mapping):
            return value
        out = []
        for name, body in value.items():
            if single is not None and not isinstance(body, Mapping):
                body = {single: body}
            if not isinstance(body, Mapping):
                raise ValueError(f"{name!r}: expected a mapping, got {body!r}")
            out.append({key: name, **body})
        return out

    return load


# --- Patterns ---

KEY: Final = "^[a-z]+:[0-9a-f]{32}$"
CANONICAL_DECIMAL: Final = r"^(?:0|-?(?:[1-9][0-9]*(?:\.[0-9]*[1-9])?|0\.[0-9]*[1-9]))$"
SENTENCE_ID: Final = "^[sc][0-9]+$"
ENTITY_KEY: Final = "^ent:[0-9a-f]{32}$"
STATEMENT_KEY: Final = "^stm:[0-9a-f]{32}$"
REFERENCE_KEY: Final = "^xrf:[0-9a-f]{32}$"
CLAIM_KEY: Final = "^clm:[0-9a-f]{32}$"
RENDITION_KEY: Final = "^ren:[0-9a-f]{32}$"
SEGMENT_KEY: Final = "^seg:[0-9a-f]{32}$"
LOCAL_NAME: Final = "^[A-Za-z_][A-Za-z0-9_]*$"
PREFIXED_NAME: Final = "^[a-z][a-z0-9_]*:[A-Za-z_][A-Za-z0-9_]*$"
MEMBER_NAME: Final = "^[a-z][a-z0-9_]*(:[a-z][a-z0-9_]*)?$"

# --- Types ---

# A D1 §10.1 key, a prefix and 32 hex digits ('clm:…').
Key = Annotated[str, Field(pattern=KEY)]
# A number as its D1 §6.2 canonical decimal string.
CanonicalDecimal = Annotated[str, Field(pattern=CANONICAL_DECIMAL)]
# A citation-frame sentence id, sN in the unit or cN in the standing context.
SentenceId = Annotated[str, Field(pattern=SENTENCE_ID), CITATION]
# An entity's key (an ExternalReference's is a ReferenceKey).
EntityKey = Annotated[str, Field(pattern=ENTITY_KEY)]
# A statement's key.
StatementKey = Annotated[str, Field(pattern=STATEMENT_KEY)]
# An ExternalReference's key.
ReferenceKey = Annotated[str, Field(pattern=REFERENCE_KEY)]
# A claim's key.
ClaimKey = Annotated[str, Field(pattern=CLAIM_KEY)]
# A rendition's key, the typed reference a stored batch and a candidate set carry.
RenditionKey = Annotated[str, Field(pattern=RENDITION_KEY)]
# A segment's key on one rendition.
SegmentKey = Annotated[str, Field(pattern=SEGMENT_KEY)]
# A string that is not empty (a local ref, an id, a quote, a selector).
NonEmpty = Annotated[str, Field(min_length=1)]
# A character offset or a count, never negative.
Offset = Annotated[int, Field(ge=0)]
# A schema element's local name, as the authored form writes it (ParameterRole).
LocalName = Annotated[str, Field(pattern=LOCAL_NAME)]
# A schema element's prefixed name, as the stored form writes it (stat:ParameterRole).
PrefixedName = Annotated[str, Field(pattern=PREFIXED_NAME)]
# A member of a schema-version-scoped closed set: a core member by its name, a pack's by
# <prefix>:<name> (S1's compiled models and S2's checks refuse what the version lacks).
MemberName = Annotated[str, Field(pattern=MEMBER_NAME)]
# An opaque JSON document (jsonb) whose structure the model does not declare.
Json = JsonValue
# A score in [0, 1].
Score = Annotated[float, Field(ge=0, le=1)]

