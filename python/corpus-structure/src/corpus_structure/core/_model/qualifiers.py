"""The core qualifiers' specifications (D1 §5.2; model and projections §3.2; TM §8).

Each core qualifier slot of `model/core.yaml` is one `QualifierSpec`: its range (the
stored range where it differs), default, key role and role condition, canonical form
(derived from the range), case policy and store placement. S1 compiles pack
qualifiers into the same type.

Generated by `corpus_structure.schema.generate` from the model (`just model generate`); do not
edit.
"""

