"""Validators of the model's `ci:invariant` declarations and slot `pattern`s (D2 §3.4;
F01).

One function per class that declares or inherits an invariant or has a slot with a
`pattern`, applying each invariant with the templates of `core/invariants.py` and
searching each present string value for its pattern. The hand-written shapes call
them in their model validators, and M2 compiles the same declarations into CHECKs.

Generated by `corpus_structure.schema.generate` from the model (`just model generate`); do not
edit.
"""

from __future__ import annotations

