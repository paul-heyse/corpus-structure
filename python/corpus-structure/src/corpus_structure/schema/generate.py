"""Stage A generation (model and projections §3.2; ADR-0020): the model's files that `core` imports.

`render(model)` returns every generated file by its path under the `corpus_structure` package:

- `core/vocab.py`: one `StrEnum` per closed set of both modules (its members expanded, §3.1), each
  member property as a frozenset of members, `LIFECYCLE` and `MEMBER_PROPERTIES`;
- `core/_model/qualifiers.py`: the core `QualifierSpec`s;
- `core/_model/names.py`: the core local <-> prefixed name tables and qualifier name constants;
- `core/_model/sql.py`: the SQL literals of the static sets' member properties;
- `core/_model/validators.py`: one validator per class with `ci:invariant`, calling
  `core/invariants.py`'s templates;
- `core/_model/revision.py`: the model revision the files were generated from.

The output is a pure function of the model and this module (`GENERATOR_VERSION`), formatted by the
repository's pinned ruff so `just turn-end` leaves it unchanged; a drift test regenerates it.
"""

from __future__ import annotations

import keyword
import re
import subprocess
import sys
import textwrap
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

from corpus_structure.schema.model import (
    GENERATOR,
    Member,
    Model,
    ModelError,
    Revision,
    View,
    ci_annotations,
    invariants_of,
    revision,
)

PACKAGE = Path(__file__).resolve().parents[1]
REPOSITORY = PACKAGE.parents[3]
HEADER = (
    '"""{doc}\n\nGenerated by `{generator}` from the model (`just model generate`); do not'
    '\nedit.\n"""'
)


def _docstring(text: str, indent: str) -> str:
    body = " ".join(text.split()).replace("\\", "\\\\").replace('"""', "'''")
    one = f'{indent}"""{body}"""'
    if len(one) <= 100:
        return one
    lines = textwrap.wrap(
        body, width=100, initial_indent=f'{indent}"""', subsequent_indent=indent,
        break_on_hyphens=False, break_long_words=False,
    )  # fmt: skip
    if len(lines) == 1:  # ruff would join a one-line body with its closing quotes
        head, _, last = lines[0].rpartition(" ")
        lines = [head, f"{indent}{last}"]
    return "\n".join(lines) + f'\n{indent}"""'


def member_name(text: str) -> str:
    name = re.sub(r"[^A-Za-z0-9]", "_", text).upper()
    if name[0].isdigit() or keyword.iskeyword(name):
        name = f"_{name}"
    return name


def _header(doc: str) -> str:
    return HEADER.format(doc=doc, generator=GENERATOR)


# --- core/vocab.py -----------------------------------------------------------------------------


def _vocab(model: Model) -> str:
    out = [
        _header(
            "Closed value sets of the model, with their member properties and lifecycles.\n\n"
            "One `StrEnum` per closed set of `model/core.yaml` and `model/system.yaml` (TM §11).\n"
            "A "
            "member property is a frozenset of the members that have it (D2 §3.4); consumers test\n"
            "membership in it, never a literal subset of members. `LIFECYCLE` gives each set's\n"
            "`ci:lifecycle`: `static` sets change with code, `schema_version` sets are extended\n"
            "by "
            "packs per schema version (their core members are listed here)."
        ),
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from enum import StrEnum",
        "from typing import Final",
        "",
    ]
    properties: dict[str, tuple[str, list[Member]]] = {}
    lifecycles: list[tuple[str, str]] = []
    for _, enum in model.enums():
        name = str(enum.name)
        members = model.expanded(name)
        lifecycle = str(ci_annotations(enum)["ci:lifecycle"])
        lifecycles.append((name, lifecycle))
        out += ["", "", f"class {name}(StrEnum):"]
        out.append(_docstring(f"{enum.description or name} Lifecycle: {lifecycle}.", "    "))
        out.append("")
        for m in members:
            out.append(f"    {member_name(m.text)} = {m.text!r}")
            for prop in m.properties:
                properties.setdefault(prop, (name, []))[1].append(m)
    out += ["", "", "# --- Member properties (D2 §3.4) ---", ""]
    for prop, (enum_name, members) in properties.items():
        items = "".join(f"        {enum_name}.{member_name(m.text)},\n" for m in members)
        out.append(
            f"{prop.upper()}: Final[frozenset[{enum_name}]] = frozenset(\n    {{\n{items}    }}\n)"
        )
    out += [
        "",
        "# Every member property by name: the declaration check and the pack compilers read it.",
        "MEMBER_PROPERTIES: Final[Mapping[str, frozenset[StrEnum]]] = {",
        *(f"    {p!r}: {p.upper()}," for p in properties),
        "}",
        "",
        "# The closed set each member property belongs to.",
        "PROPERTY_OF: Final[Mapping[str, type[StrEnum]]] = {",
        *(f"    {p!r}: {e}," for p, (e, _) in properties.items()),
        "}",
        "",
        "LIFECYCLE: Final[Mapping[type[StrEnum], Lifecycle]] = {",
        *(f"    {n}: Lifecycle.{member_name(lc)}," for n, lc in lifecycles),
        "}",
    ]
    return "\n".join(out) + "\n"


# --- core/_model/qualifiers.py -----------------------------------------------------------------


def _canonical(view: View, rng: str, slot: Any) -> str:
    """A qualifier's canonical form, derived from its (stored) range (D1 §6.2)."""
    if view.get_enum(rng) is not None:
        return "member"
    ancestors = set(view.class_ancestors(rng)) if view.get_class(rng) else set()
    if rng == "StoredScope":
        return "scope"
    if "Condition" in ancestors:
        return "condition"
    if "Entity" in ancestors:
        return "entity_key"
    if "MapEntry" in ancestors:
        return "map"
    by_class = {
        "Formula": "token_form", "SetExpr": "token_form", "TextValue": "text_form",
        "PhraseValue": "text_form", "IntervalValue": "interval", "NumberValue": "number",
        "EnumValue": "enum", "DateValue": "verbatim", "BoolValue": "verbatim",
    }  # fmt: skip
    if rng in by_class:
        return by_class[rng]
    if "ci:case" in ci_annotations(slot):
        return "identifier"
    return "verbatim"


def _store(view: View, rng: str, slot: Any) -> str:
    declared = ci_annotations(slot).get("ci:store")
    if declared is not None:
        return {"nested": "json", "edge": "edge", "table": "column"}[str(declared)]
    if view.get_enum(rng) is not None:
        return "column"
    if view.get_class(rng) and "Entity" in view.class_ancestors(rng):
        return "column"
    return "json"


def qualifier_specs(view: View) -> list[dict[str, Any]]:
    """The core qualifier specifications, in declaration order (model and projections §3.2)."""
    specs = []
    for name, slot in view.schema.slots.items():
        ann = ci_annotations(slot)
        if ann.get("ci:role") != "qualifier":
            continue
        rng = str(ann.get("ci:stored_range") or slot.range)
        default = None
        if slot.ifabsent:
            m = re.fullmatch(r"string\((.*)\)", str(slot.ifabsent))
            if not m:
                raise ModelError(
                    [f"core.slots.{name}: ifabsent {slot.ifabsent!r} is not string(…)"]
                )
            default = (str(slot.range), m.group(1))
        specs.append({
            "name": f"core:{name}",
            "local_name": str(name),
            "range": rng,
            "default": default,
            "key_role": str(ann["ci:key_role"]),
            "key_role_when": ann.get("ci:key_role_when"),
            "canonical": _canonical(view, rng, slot),
            "case": str(ann.get("ci:case", "fold")),
            "store": _store(view, rng, slot),
        })  # fmt: skip
    return specs


def _qualifiers(model: Model) -> str:
    specs = qualifier_specs(model.core)
    enums = sorted(
        {s["default"][0] for s in specs if s["default"]}
        | {"CanonicalForm", "CaseRule", "KeyRole", "QualifierStore"}
    )
    out = [
        _header(
            "The core qualifiers' specifications (D1 §5.2; model and projections §3.2; TM §8).\n\n"
            "Each core qualifier slot of `model/core.yaml` is one `QualifierSpec`: its range (the\n"
            "stored range where it differs), default, key role and role condition, canonical form\n"
            "(derived from the range), case policy and store placement. S1 compiles pack\n"
            "qualifiers into the same type."
        ),
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from dataclasses import dataclass",
        "from typing import Any, Final",
        "",
        "from pydantic import MISSING",
        "",
        f"from corpus_structure.core.vocab import {', '.join(enums)}",
        "",
        "",
        "@dataclass(frozen=True, slots=True)",
        "class QualifierSpec:",
        '    """One qualifier\'s specification; `default` is `MISSING` when it has none."""',
        "",
        "    name: str",
        "    local_name: str",
        "    range: str",
        "    default: Any",
        "    key_role: KeyRole",
        "    key_role_when: str | None",
        "    canonical: CanonicalForm",
        "    case: CaseRule",
        "    store: QualifierStore",
        "",
        "",
        "CORE_QUALIFIERS: Final[tuple[QualifierSpec, ...]] = (",
    ]
    for s in specs:
        default = f"{s['default'][0]}.{member_name(s['default'][1])}" if s["default"] else "MISSING"
        when = repr(s["key_role_when"]) if s["key_role_when"] else "None"
        out += [
            "    QualifierSpec(",
            f"        name={s['name']!r},",
            f"        local_name={s['local_name']!r},",
            f"        range={s['range']!r},",
            f"        default={default},",
            f"        key_role=KeyRole.{member_name(s['key_role'])},",
            f"        key_role_when={when},",
            f"        canonical=CanonicalForm.{member_name(s['canonical'])},",
            f"        case=CaseRule.{member_name(s['case'])},",
            f"        store=QualifierStore.{member_name(s['store'])},",
            "    ),",
        ]
    out += [
        ")",
        "",
        "# By stored (prefixed) name.",
        "BY_NAME: Final[Mapping[str, QualifierSpec]] = {q.name: q for q in CORE_QUALIFIERS}",
    ]
    return "\n".join(out) + "\n"


# --- core/_model/names.py ----------------------------------------------------------------------


def _names(model: Model) -> str:
    view = model.core
    entity_classes = [
        str(n) for n, c in view.schema.classes.items()
        if "Entity" in view.class_ancestors(str(n)) and not c.abstract
    ]  # fmt: skip
    predicates, qualifiers = [], []
    for name, slot in view.schema.slots.items():
        role = ci_annotations(slot).get("ci:role")
        if role == "predicate":
            predicates.append(str(name))
        elif role == "qualifier":
            qualifiers.append(str(name))
    local = [*entity_classes, *predicates, *qualifiers]

    def tup(names: Iterable[str]) -> str:
        items = "".join(f"    {n!r},\n" for n in names)
        return f"(\n{items})"

    out = [
        _header(
            "The core half of the local <-> prefixed name tables (X2-01; D2 §4).\n\n"
            "The authored batch names schema elements locally, the stored form by prefixed name.\n"
            "These are core's entity classes, predicates and qualifiers; S1 adds a pack's."
        ),
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from typing import Final",
        "",
        'PREFIX: Final = "core"',
        "",
        f"ENTITY_CLASSES: Final[tuple[str, ...]] = {tup(entity_classes)}",
        f"PREDICATES: Final[tuple[str, ...]] = {tup(predicates)}",
        "# The core qualifiers by local name, in declaration order, and by stored name.",
        f"QUALIFIERS: Final[tuple[str, ...]] = {tup(qualifiers)}",
        f"STORED_QUALIFIERS: Final[tuple[str, ...]] = {tup(f'core:{q}' for q in qualifiers)}",
        "",
        "# Each core qualifier's stored name.",
        *(f"{q.upper()}: Final = {f'core:{q}'!r}" for q in qualifiers),
        "",
        "LOCAL_TO_PREFIXED: Final[Mapping[str, str]] = {",
        *(f"    {n!r}: {f'core:{n}'!r}," for n in local),
        "}",
        "PREFIXED_TO_LOCAL: Final[Mapping[str, str]] = {",
        "    v: k for k, v in LOCAL_TO_PREFIXED.items()",
        "}",
    ]
    return "\n".join(out) + "\n"


# --- core/_model/sql.py ------------------------------------------------------------------------


def _sql(model: Model) -> str:
    out = [
        _header(
            "SQL literals of the static closed sets' member properties (model and projections\n"
            "§3.2), for the overlay's partial predicates and the D3 §9 queries: each property's\n"
            "members as a tuple, and as an SQL `IN` list (`kind IN {SEARCH_BLOCK_IN}`)."
        ),
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Iterable",
        "from typing import Final",
        "",
        "",
        "def in_list(members: Iterable[str]) -> str:",
        '    """An SQL `IN` list of string literals: `(\'a\', \'b\')`."""',
        '    return "(" + ", ".join(f"\'{m}\'" for m in members) + ")"',
        "",
        "",
    ]
    for _, enum in model.enums():
        if ci_annotations(enum)["ci:lifecycle"] != "static":
            continue
        props: dict[str, list[str]] = {}
        for m in model.expanded(str(enum.name)):
            for p in m.properties:
                props.setdefault(p, []).append(m.text)
        for prop, texts in props.items():
            items = "".join(f"    {t!r},\n" for t in texts)
            out += [
                f"# {enum.name} members with the property {prop}.",
                f"{prop.upper()}: Final[tuple[str, ...]] = (\n{items})",
                f"{prop.upper()}_IN: Final = in_list({prop.upper()})",
                "",
            ]
    return "\n".join(out).rstrip() + "\n"


# --- core/_model/validators.py -----------------------------------------------------------------


def _snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def _literal(view: View, cls: str, slot: str, text: str) -> str:
    rng = view.induced_slot(slot, cls).range
    if rng in ("integer", "SmallInt", "Id"):
        return str(int(text))
    return repr(text)


def _validators(model: Model) -> str:
    view = model.system
    out = [
        _header(
            "Validators of the model's `ci:invariant` declarations (D2 §3.4; F01).\n\n"
            "One function per class that declares or inherits an invariant, applying each with\n"
            "the templates of `core/invariants.py`. The hand-written shapes call them in their\n"
            "model validators, and M2 compiles the same declarations into CHECKs."
        ),
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Callable, Mapping",
        "from typing import Final",
        "",
        "from corpus_structure.core import invariants",
        "",
    ]
    registry: list[tuple[str, str, list[str]]] = []
    for _, module_view in model.modules():
        for name in module_view.schema.classes:
            cls = str(name)
            invs = invariants_of(view, cls)
            if not invs:
                continue
            fn = _snake(cls)
            body = []
            for inv in invs:
                if inv.condition is None:
                    args = ", ".join(repr(f) for f in inv.fields)
                    body.append(f"    invariants.{inv.template}(obj, {args})")
                else:
                    values = ", ".join(_literal(view, cls, inv.condition, v) for v in inv.values)
                    values += "," if len(inv.values) == 1 else ""
                    body.append(
                        f"    invariants.{inv.template}(obj, {inv.fields[0]!r}, "
                        f"{inv.condition!r}, ({values}))"
                    )
            declared = "; ".join(str(i) for i in invs)
            out += [
                "",
                "",
                f"def {fn}(obj: object) -> None:",
                _docstring(f"{cls}: {declared}.", "    "),
                *body,
            ]
            registry.append((cls, fn, [str(i) for i in invs]))
    out += [
        "",
        "",
        "# Class -> its validator, and class -> its declared invariants as written.",
        "VALIDATORS: Final[Mapping[str, Callable[[object], None]]] = {",
        *(f"    {c!r}: {f}," for c, f, _ in registry),
        "}",
        "INVARIANTS: Final[Mapping[str, tuple[str, ...]]] = {",
        *(f"    {c!r}: ({', '.join(repr(i) for i in invs)},)," for c, _, invs in registry),
        "}",
    ]
    return "\n".join(out) + "\n"


# --- core/_model/revision.py -------------------------------------------------------------------


def _revision(current: Revision) -> str:
    out = [
        _header(
            "The model revision the generated files were generated from (TM §2; model and\n"
            "projections §3.1). `model/revisions.yaml` is the authority; S1b's `ensure` writes\n"
            "it to `meta.model_revision`, and runs record it."
        ),
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from typing import Final",
        "",
        f"LABEL: Final = {current.label!r}",
        f"CONTENT_HASH: Final = {current.content_hash!r}",
        f"KEY_SCHEME: Final = {current.key_scheme}",
        "COMPILERS: Final[Mapping[str, str]] = {",
        *(f"    {k!r}: {v!r}," for k, v in sorted(current.compilers.items())),
        "}",
    ]
    return "\n".join(out) + "\n"


# --- Rendering and formatting ------------------------------------------------------------------


def _model_init() -> str:
    return (
        _header(
            "Stage A's generated model facts that `core` imports (model and projections §3.2):\n"
            "`qualifiers`, `names`, `sql`, `validators` and `revision`."
        )
        + "\n"
    )


def _format(path: str, text: str) -> str:
    """The text as the repository's ruff leaves it (`just turn-end` runs the same two steps)."""
    for args in (["check", "--fix", "--quiet", "--exit-zero"], ["format"]):
        done = subprocess.run(
            [sys.executable, "-m", "ruff", *args, "--stdin-filename", path, "-"],
            input=text, capture_output=True, text=True, cwd=REPOSITORY, check=False,
        )  # fmt: skip
        if done.returncode != 0:
            raise RuntimeError(f"ruff {args[0]} failed on {path}: {done.stderr}")
        text = done.stdout
    return text


def render(model: Model) -> dict[str, str]:
    """Every generated file's text by its path relative to the `corpus_structure` package."""
    current = revision(model)
    raw = {
        "core/vocab.py": _vocab(model),
        "core/_model/__init__.py": _model_init(),
        "core/_model/qualifiers.py": _qualifiers(model),
        "core/_model/names.py": _names(model),
        "core/_model/sql.py": _sql(model),
        "core/_model/validators.py": _validators(model),
        "core/_model/revision.py": _revision(current),
    }
    return {path: _format(str(PACKAGE / path), text) for path, text in raw.items()}


def write(files: Mapping[str, str], root: Path = PACKAGE) -> list[str]:
    """Write the files under `root`; the paths whose content changed."""
    changed = []
    for rel, text in files.items():
        path = root / rel
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            changed.append(rel)
    return changed


def drift(files: Mapping[str, str], root: Path = PACKAGE) -> list[str]:
    """The generated paths whose committed file differs from the regenerated text."""
    return [
        rel for rel, text in files.items()
        if not (root / rel).exists() or (root / rel).read_text(encoding="utf-8") != text
    ]  # fmt: skip
