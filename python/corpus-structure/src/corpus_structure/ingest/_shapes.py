"""The source-profile classes (D2 §12.1; D4 M01; ingest and math §3.2).

Generated from `model/system.yaml`'s `SourceProfile` and the classes it reaches
(`schema/stage_b.py` states the rules); their behaviour is hand-written in
`ingest/profile_support.py`, and `ingest/profile.py` loads, checks and compiles profiles.

Generated by `corpus_structure.schema.stage_b` from the model (`just model generate`); do not
edit.
"""

from __future__ import annotations

from typing import Annotated, Self

from pydantic import AfterValidator, BeforeValidator, Field, model_validator

from corpus_structure.core._model.types import CoreModel, NonEmpty, keyed
from corpus_structure.core.vocab import (
    FigureRender,
    ListMarkerStyle,
    QuoteRender,
    ReferenceRender,
    SectionSource,
    SegmentKind,
    StatementKind,
    SummaryRender,
    SynthesisEvidence,
    SynthesisObject,
)
from corpus_structure.ingest import profile_support


class CorpusIndex(CoreModel):
    """The corpus index of a source profile."""

    file: NonEmpty
    page: NonEmpty
    first_pass: str | None = None


class ExcludeRule(CoreModel):
    """A named exclusion rule; excluded text is recorded per rule (D4 M01)."""

    name: NonEmpty
    selector: NonEmpty


class BlockHint(CoreModel):
    """A statement-kind hint for blocks of one selector."""

    selector: NonEmpty
    statement_kind: Annotated[StatementKind | str, BeforeValidator(profile_support.statement_kind)]
    claim_bearing: bool | None = None


class SectionHint(CoreModel):
    """The statement kind of units under a section title."""

    title: NonEmpty
    statement_kind: Annotated[StatementKind | str, BeforeValidator(profile_support.statement_kind)]


class SummaryKind(CoreModel):
    """The statement kind of details blocks with one summary text."""

    summary: NonEmpty
    statement_kind: Annotated[StatementKind | str, BeforeValidator(profile_support.statement_kind)]


class SynthesisRule(CoreModel):
    """The claim a block's containment states (D5 §3.5)."""

    statement_kind: Annotated[StatementKind | str, BeforeValidator(profile_support.statement_kind)]
    predicate: Annotated[str, BeforeValidator(profile_support.predicate)]
    object: SynthesisObject
    evidence: SynthesisEvidence


class DetailsKinds(profile_support.DetailsKindsMethods, CoreModel):
    """How details blocks become statements, and the claims their containment states."""

    default: Annotated[StatementKind | str, BeforeValidator(profile_support.statement_kind)]
    inside_example_or_exercise: (
        Annotated[StatementKind | str, BeforeValidator(profile_support.statement_kind)] | None
    ) = None
    by_summary: Annotated[
        tuple[SummaryKind, ...], BeforeValidator(keyed("summary", "statement_kind"))
    ] = ()
    synthesize: Annotated[tuple[SynthesisRule, ...], BeforeValidator(keyed("statement_kind"))] = ()

    @model_validator(mode="after")
    def _hooks(self) -> Self:
        profile_support.one_entry_per_key(self)
        return self


class MathSpec(profile_support.MathSpecMethods, CoreModel):
    """Math delimiters, bare display environments and the page macro source (D4 M01 `math`)."""

    inline: tuple[str, str] | None = ("\\(", "\\)")
    display: tuple[str, str] | None = ("\\[", "\\]")
    display_environments: tuple[str, ...] = ()
    page_macros: NonEmpty | None = None

    @model_validator(mode="after")
    def _hooks(self) -> Self:
        profile_support.delimiters(self)
        return self


class ReferenceSpec(CoreModel):
    """In-text reference links and their rendering (D1 §3.1; D4 M01 `references`)."""

    selector: NonEmpty
    render: ReferenceRender = ReferenceRender.BROWSER


class ListMarkerRule(CoreModel):
    """The item markers of the lists one selector matches."""

    selector: NonEmpty
    style: ListMarkerStyle


class RenderSpec(CoreModel):
    """Rendering conventions for script- or style-produced text (D4 M01 `render`)."""

    q: QuoteRender = QuoteRender.BARE
    list_markers: Annotated[
        tuple[ListMarkerRule, ...], BeforeValidator(keyed("selector", "style"))
    ] = ()
    summary: SummaryRender = SummaryRender.HEADING
    figure: FigureRender = FigureRender.CAPTION


class SourceProfile(profile_support.SourceProfileMethods, CoreModel):
    """A source's HTML conventions and its place in the corpus (`sources/<profile>.yaml`; D2 §12.1,
    D4 M01).
    """

    version: NonEmpty
    root: Annotated[NonEmpty, AfterValidator(profile_support.relative_root)]
    index: CorpusIndex | None = None
    language: str = "english"
    applies_to: NonEmpty
    encoding: NonEmpty = "sniff"
    exclude: Annotated[tuple[ExcludeRule, ...], BeforeValidator(keyed("name", "selector"))] = (
        ExcludeRule(name="scripts", selector="script, noscript"),
    )
    title: NonEmpty = "h1"
    sections: tuple[NonEmpty, ...] = ("h1", "h2", "h3", "h4", "h5", "h6")
    section_source: SectionSource = SectionSource.BODY
    unit: NonEmpty | None = None
    layout: tuple[NonEmpty, ...] = ()
    block_hints: Annotated[tuple[BlockHint, ...], BeforeValidator(keyed("selector"))] = ()
    section_hints: Annotated[
        tuple[SectionHint, ...], BeforeValidator(keyed("title", "statement_kind"))
    ] = ()
    details_kinds: DetailsKinds = DetailsKinds(default=StatementKind.PROOF)
    math: MathSpec = Field(default_factory=MathSpec)
    references: ReferenceSpec | None = None
    render: RenderSpec = Field(default_factory=RenderSpec)
    verbatim: tuple[NonEmpty, ...] = ()
    img_alt: bool | None = None
    orphan_text: SegmentKind = SegmentKind.PARAGRAPH

    @model_validator(mode="after")
    def _hooks(self) -> Self:
        profile_support.consistent(self)
        return self


